/** The hand-picked list for a city, matched by id or, failing that, by name. */
export function picksFor(city: number | string | null | undefined): CityPicks | undefined {
  if (city == null) return undefined
  if (typeof city === 'number') return PICKS.find((c) => c.cityId === city)
  const name = city.trim().toLowerCase()
  return PICKS.find((c) => c.city.toLowerCase() === name)
}

/** A map search for a pick, so members can see where it is. */
export const mapLink = (pick: Pick, city: string) =>
  `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(`${pick.title}, ${city}`)}`

