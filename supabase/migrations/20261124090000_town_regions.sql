-- The county comes back with each town. Text after a comma narrows by county or country.
drop function public.search_cities(text);
create function public.search_cities(q text)
returns table (id integer, name text, country_code char(2), region text)
language sql
stable
security definer
set search_path = ''
as $$
  with typed as (
    select replace(replace(lower(extensions.unaccent(btrim(split_part(q, ',', 1)))), '%', ''), '_', '\_') || '%' as pattern,
           nullif(replace(replace(lower(extensions.unaccent(btrim(split_part(q, ',', 2)))), '%', ''), '_', '\_'), '') as area
  )
  select c.id, c.name, c.country_code, c.region
  from public.cities c, typed
  where char_length(btrim(split_part(q, ',', 1))) >= 2
    and (c.search_name like typed.pattern
         or c.id in (select a.city_id from public.city_aliases a where a.search_name like typed.pattern))
    and (typed.area is null
         or lower(extensions.unaccent(coalesce(c.region, ''))) like typed.area || '%'
         or lower(c.country_code) = typed.area)
  order by c.population desc
  limit 8;
$$;
revoke all on function public.search_cities(text) from public, anon;
grant execute on function public.search_cities(text) to authenticated;
