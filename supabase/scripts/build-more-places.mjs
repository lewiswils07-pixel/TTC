// More places to pick (Lewis, 24 Oct): every town in Europe with 1,000+
// people and every town elsewhere with 15,000+, from GeoNames (CC BY 4.0,
// credit "GeoNames, geonames.org") via the all-the-cities package, with the
// region (like Campania or Bavaria) from the cities.json package, so towns
// with the same name can be told apart in the search.
//
//   cd supabase/scripts && npm i --no-save all-the-cities cities.json && node build-more-places.mjs
//
// Writes supabase/migrations/20261202090000_more_places.sql. Places already
// on the list (by id, or the same name close by) aren't added twice.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

const require = createRequire(import.meta.url)
const cities = require('all-the-cities')
const admin1 = new Map(require('cities.json/admin1.json').map((a) => [a.code, a.name]))

const EUROPE = new Set(
  ('AD AL AT AX BA BE BG BY CH CY CZ DE DK EE ES FI FO FR GB GG GI GR HR HU IE IM IS IT JE LI LT LU LV MC MD ME MK MT NL NO PL PT RO RS SE SI SJ SK SM TR UA VA XK').split(' '),
)
// The same as searchName in build-cities.mjs (importing it would rerun that script).
const EXTRA = { ø: 'o', ł: 'l', ß: 'ss', æ: 'ae', œ: 'oe', đ: 'd', ı: 'i', þ: 'th', ð: 'd' }
const searchName = (name) =>
  name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[øłßæœđıþð]/g, (c) => EXTRA[c])

const already = (c) => (EUROPE.has(c.country) ? c.population >= 15000 : c.population >= 100000 || c.featureCode === 'PPLC')
const wanted = (c) => (EUROPE.has(c.country) ? c.population >= 1000 : c.population >= 15000)
// UK towns were added on 11 Oct (build-uk-towns.mjs), with their counties.
const keep = cities.filter((c) => c.country !== 'GB' && wanted(c) && !already(c)).sort((a, b) => a.cityId - b.cityId)

const q = (s) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`)
const rows = keep.map((c) => {
  const [lng, lat] = c.loc.coordinates
  const region = admin1.get(`${c.country}.${c.adminCode}`) ?? null
  return `(${c.cityId},${q(c.name)},${q(c.country)},${lat},${lng},${c.population},${q(searchName(c.name))},${q(region && region !== c.name ? region : null)})`
})

const PER_FILE = 12000
const parts = []
for (let i = 0; i < rows.length; i += PER_FILE) parts.push(rows.slice(i, i + PER_FILE))
const insert = (chunk) => `insert into public.cities (id, name, country_code, lat, lng, population, search_name, region)
select v.id, v.name, v.cc, v.lat, v.lng, v.population, v.search_name, v.region
from (values
${chunk.join(',\n')}
) as v(id, name, cc, lat, lng, population, search_name, region)
where not exists (select 1 from public.cities c
                   where c.country_code = v.cc and c.search_name = v.search_name
                     and abs(c.lat - v.lat) < 0.15 and abs(c.lng - v.lng) < 0.25)
on conflict (id) do nothing;`
const body = parts
  .map((part, n) => {
    const chunks = []
    for (let i = 0; i < part.length; i += 1000) chunks.push(insert(part.slice(i, i + 1000)))
    return `-- Part ${n + 1} of ${parts.length}\n${chunks.join('\n\n')}`
  })
  .join('\n\n')

const sql = `-- More places to pick: ${keep.length} towns (Lewis, 24 Oct). Every town in
-- Europe with 1,000+ people and every town elsewhere with 15,000+.
-- Generated by supabase/scripts/build-more-places.mjs. Do not edit by hand.
-- Data: GeoNames (geonames.org), CC BY 4.0.

-- Finding places near a trip looks places up by latitude first.
create index if not exists cities_lat_idx on public.cities (lat);

${body}
`
writeFileSync(new URL('../migrations/20261202090000_more_places.sql', import.meta.url), sql)
console.log(`Wrote ${keep.length} places in ${parts.length} parts`)
