// Adds the UK's smaller towns and villages (1,000+ people, plus council
// towns) to the cities list, so members can pick where they really live
// (Lewis, 11 Oct). Bigger places are already there.
//
//   cd supabase/scripts && npm i --no-save all-the-cities && node build-uk-towns.mjs
//
// Writes supabase/migrations/20261119090000_uk_towns.sql.
// Data: GeoNames (geonames.org), CC BY 4.0.
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'

// The same as searchName in build-cities.mjs (importing it would rerun that script).
const EXTRA = { ø: 'o', ł: 'l', ß: 'ss', æ: 'ae', œ: 'oe', đ: 'd', ı: 'i', þ: 'th', ð: 'd' }
const searchName = (name) =>
  name
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[øłßæœđıþð]/g, (c) => EXTRA[c])

const cities = createRequire(import.meta.url)('all-the-cities')
const keep = cities
  .filter((c) => c.country === 'GB' && c.population < 15000 && (c.population >= 1000 || /^PPLA/.test(c.featureCode)))
  .sort((a, b) => a.cityId - b.cityId)

const q = (s) => `'${s.replace(/'/g, "''")}'`
const rows = keep.map((c) => {
  const [lng, lat] = c.loc.coordinates
  return `(${c.cityId},${q(c.name)},${lat},${lng},${c.population},${q(searchName(c.name))})`
})
const chunks = []
for (let i = 0; i < rows.length; i += 1000) chunks.push(rows.slice(i, i + 1000))

const sql = `-- UK towns and villages: ${keep.length} more places to pick (Lewis, 11 Oct).
-- Generated by supabase/scripts/build-uk-towns.mjs. Do not edit by hand.
-- Data: GeoNames (geonames.org), CC BY 4.0. A place already on the list
-- under the same name nearby (added by hand earlier) isn't added twice.

${chunks
  .map(
    (chunk) =>
      `insert into public.cities (id, name, country_code, lat, lng, population, search_name)
select v.id, v.name, 'GB', v.lat, v.lng, v.population, v.search_name
from (values
${chunk.join(',\n')}
) as v(id, name, lat, lng, population, search_name)
where not exists (select 1 from public.cities c
                   where c.country_code = 'GB' and c.search_name = v.search_name
                     and abs(c.lat - v.lat) < 0.15 and abs(c.lng - v.lng) < 0.25)
on conflict (id) do nothing;`,
  )
  .join('\n\n')}
`
writeFileSync(new URL('../migrations/20261119090000_uk_towns.sql', import.meta.url), sql)
console.log(`Wrote ${keep.length} UK towns`)
